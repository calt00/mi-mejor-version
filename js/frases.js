// Devuelve n frases sin repetir hasta agotar la lista.
export async function frasesLocales(n) {
  let usadas = await kvGet('frasesUsadas', []);
  const out = [];
  for (let i = 0; i < n; i++) {
    let disponibles = FRASES.map((_, j) => j).filter(j => !usadas.includes(j));
    if (!disponibles.length) { usadas = []; disponibles = FRASES.map((_, j) => j); }
    const j = disponibles[Math.floor(Math.random() * disponibles.length)];
    usadas.push(j);
    out.push(FRASES[j]);
  }
  await kvSet('frasesUsadas', usadas);
  return out;
}
